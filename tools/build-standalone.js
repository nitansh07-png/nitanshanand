#!/usr/bin/env node
/* =========================================================================
   build-standalone.js

   Folds agent-mode.html and everything it references into one HTML file.
   The page itself stays the source of truth: edit agent-mode.html and run
   this again rather than touching the generated file.

   What gets inlined: both stylesheets, all four scripts (in the order they
   would have executed), and any local image the CSS or the markup asks for,
   as data URIs.

   What stays a request: the Google Fonts, and the videos. The hero and
   footer clips live on a CDN, and the Unfinished World preview is a 4.3 MB
   local file that would roughly twenty-times the size of this document for
   a clip most readers will never scroll to. Pass --inline-video if you want
   it folded in anyway.

   Usage:  node tools/build-standalone.js [--inline-video]
   ========================================================================= */

'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'agent-mode.html');
const OUT = path.join(ROOT, 'agent-mode-standalone.html');
const INLINE_VIDEO = process.argv.includes('--inline-video');

const must = (c, m) => { if (!c) throw new Error('FAILED: ' + m); };
const read = f => fs.readFileSync(path.join(ROOT, f), 'utf8');

const MIME = {
  '.png': 'image/png', '.jpg': 'image/jpeg', '.jpeg': 'image/jpeg',
  '.webp': 'image/webp', '.gif': 'image/gif', '.svg': 'image/svg+xml',
  '.mp4': 'video/mp4', '.woff2': 'font/woff2'
};
function dataUri(rel) {
  const file = path.join(ROOT, rel);
  must(fs.existsSync(file), 'missing asset: ' + rel);
  const ext = path.extname(rel).toLowerCase();
  must(MIME[ext], 'unknown asset type: ' + rel);
  return 'data:' + MIME[ext] + ';base64,' + fs.readFileSync(file).toString('base64');
}

let h = read('agent-mode.html');
const inlined = [];

/* ---------- stylesheets ---------- */
const CSS_FILES = ['styles.css', 'agent-mode.css'];
let css = CSS_FILES.map(f => '/* ---- ' + f + ' ---- */\n\n' + read(f)).join('\n\n');

/* Local images the stylesheets ask for. portrait.jpg alone is referenced six
   times, so inlining at each call site would carry six copies of the same
   base64. Each distinct asset becomes one custom property instead, and the
   call sites reference it. */
const cssAssets = new Map();
css = css.replace(/url\((['"]?)(assets\/[^)'"]+)\1\)/g, (all, q, rel) => {
  if (!cssAssets.has(rel)) {
    cssAssets.set(rel, '--img-' + path.basename(rel).replace(/\W+/g, '-'));
    inlined.push(rel);
  }
  return 'var(' + cssAssets.get(rel) + ')';
});
if (cssAssets.size) {
  const vars = [...cssAssets].map(([rel, name]) => '  ' + name + ': url("' + dataUri(rel) + '");');
  css = '/* ---- inlined assets ---- */\n:root {\n' + vars.join('\n') + '\n}\n\n' + css;
}

for (const f of CSS_FILES) {
  const tag = '<link rel="stylesheet" href="' + f + '" />';
  must(h.split(tag).length - 1 === 1, 'stylesheet link: ' + f);
  h = h.replace(tag, f === CSS_FILES[0] ? '<style>\n' + css + '\n</style>' : '');
}
// the blank line the second link left behind
h = h.replace(/<\/style>\n\n/, '</style>\n');

/* ---------- scripts, in the order they would have run ----------
   The end-of-body scripts run while parsing; analytics.js is deferred in the
   head, so it runs after them. One bundle at the end preserves that. */
const JS_ORDER = ['claude-usage.js', 'analytics.js', 'script.js', 'agent-mode.js'];
const SRC_TAGS = [
  '<script src="analytics.js" defer></script>',
  '<script src="claude-usage.js"></script>',
  '<script src="script.js"></script>',
  '<script src="agent-mode.js"></script>'
];
for (const tag of SRC_TAGS) {
  must(h.split(tag).length - 1 === 1, 'script tag: ' + tag);
  h = h.replace(tag, '');
}
const bundle = JS_ORDER.map(f => '/* ---- ' + f + ' ---- */\n\n' + read(f)).join('\n\n');
must(h.indexOf('</body>') > 0, '</body>');
h = h.replace(/\s*<\/body>/, '\n<script>\n' + bundle + '\n</script>\n\n</body>');

/* ---------- local media in the markup ---------- */
h = h.replace(/(\ssrc=")(assets\/[^"]+)(")/g, (all, a, rel, b) => {
  inlined.push(rel);
  return a + dataUri(rel) + b;
});
if (INLINE_VIDEO) {
  h = h.replace(/(\sdata-src=")(assets\/[^"]+\.mp4)(")/g, (all, a, rel, b) => {
    inlined.push(rel);
    return a + dataUri(rel) + b;
  });
}
const externalVideo = (h.match(/(?:data-)?src="assets\/[^"]+\.mp4"/g) || []);

/* ---------- the note at the top ---------- */
const banner = `<!doctype html>
<!--
  Agent mode — standalone.

  Generated by tools/build-standalone.js from agent-mode.html; edit that page
  and regenerate rather than editing this file. Everything is inlined except
  the Google Fonts, the hero and footer video and their posters${
    externalVideo.length ? `, and the
  Unfinished World preview clip (assets/unfinished-world-preview.mp4), which
  stays a relative reference so this file does not carry 4.3 MB of video.
  Run with --inline-video to fold it in` : ''}.

  The nav links point at index.html. Put this file beside the portfolio or
  repoint them before sharing it on its own.
-->`;
must(h.indexOf('<!doctype html>') === 0, 'doctype first');
const afterDoctype = h.indexOf('<html');
must(afterDoctype > 0, '<html>');
h = banner + '\n' + h.slice(afterDoctype);

/* ---------- checks ---------- */
must(h.indexOf('<link rel="stylesheet" href="styles.css"') === -1, 'css link gone');
must(h.indexOf('<script src=') === -1, 'no external scripts left');
must(h.indexOf('url("assets/') === -1 && h.indexOf("url('assets/") === -1, 'no css asset refs left');
must(h.indexOf('CLAUDE_USAGE') > 0, 'usage data present');
must(h.indexOf('id="built"') > 0 && h.indexOf('id="details"') > 0, 'both sections present');
must((h.match(/<style/g) || []).length === 1, 'one style block');

fs.writeFileSync(OUT, h, 'utf8');

console.log('wrote        ' + path.relative(ROOT, OUT));
console.log('size         ' + (h.length / 1024).toFixed(0) + ' KB');
console.log('css          ' + CSS_FILES.join(', '));
console.log('js           ' + JS_ORDER.join(', '));
console.log('inlined      ' + (inlined.length ? [...new Set(inlined)].join(', ') : 'none'));
console.log('left as refs ' + (externalVideo.length ? externalVideo.join(', ') : 'none') +
            '  + google fonts, cloudfront video');
